/*
 *      我们在理解指针的时候看到*这个符号，不要整体理解*p，而是去理解这是一个标记，
 * 程序在运行的时候是通过*这个符号来告诉程序这里我们要的不是p的值，而是通过拿p这个变量中的内容作为地址，
 * 去主存的虚拟空间取或者更改那个值。
 *      多重指针也可以这样理解 *(*p)：我们先用换元法，把内层的 (*p) 看作一个整体变量 m。
 * 那么此时 *m 的操作就很清晰了：就是把 m 的值当作地址，去主存空间进行读写。
 * 进一步追问，m 是从哪来的？它是顺着 p 中存放的地址找过去，从那个空间里取出来的值（一个一级指针）。
 */


// int *p 是声明这是一个指针变量，p存的是地址，而*p是地址上的内容。

// 变量
void var() {
    int a = 5; //将一个值赋值给变量a
    int *p = &a; //获取变量a的地址
    int *tmp = p; //定义一个临时的指针变量来存p的值，也就是a的地址

    printf("%d\n", *p);//这里打印的是a的值。
    //修改p的值，指的是修改这个地址

    p += sizeof(int) * 5; //增加几个int长度
    // 指针加法不是按字节加，而是按“指向类型的大小”缩放
    // 这里其实是算向后增加了20个int长度

    *p = 100; //这里更改的是p指向的那块地址的内存中的内容
    printf("%d\n", *p);
    p = tmp;
    printf("%d\n", *p);
}


// 数组名 a 在大多数表达式中会转换为指向首元素的指针，其值等于 &a[0]。
// 但 a 本身是数组类型，不是指针变量，不能被赋值。
// a[n] 等价于 *(a + n)。
// 指针加法 a + n 会按 a 所指向类型的大小缩放；
// 对 int 数组来说，地址偏移 n * sizeof(int) 字节。
void arr() {
    int a[10];
    for (int i = 0; i < 10; ++i) a[i] = 0;
    a[0] = 5;
    printf("*(a + n) = %d\n", *(a + 0));//这个也是合法有效的！

    int *p = a; // 这里是将 a（即 a[0] 的地址）赋给指针 p，所以 p 指向了 a[0]。
    printf("%d\n", *p);

    printf("a[1]=%d (before change)\n", a[1]);
    p = &a[1];//这里是将指针的值记为了a[1]这个值的地址。
    *p = 20;
    printf("a[1]=%d (changed, use *p find value)\n", *p);
    printf("a[1]=%d (changed, use a[1] find value)\n", a[1]);

    printf("=====================\n");

    p++;
    //这里自增是按照定义时的变量的字节长度来增加的，也就是一个数组中值占多少个字节，它自然而然地指向了a[2]
    *p = 666;
    for (int i = 0; i < 10; ++i) printf("a[%d]=%d\n", i, a[i]);
}

int main() {
    //var();
    arr();
    return 0;
}
